function inPoly(lon, lat, poly) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) c = !c;
  }
  return c;
}

export function rasterLand(name, seed) {
  const [W, H] = MAP_SIZE[name], r = rng(seed ^ 0x51ed270b);
  const land = [];
  for (let x = 0; x < W; x++) land[x] = new Array(H).fill(false);
  if (BBOX[name]) {
    const [lon0, lon1, lat0, lat1] = BBOX[name];
    for (let x = 0; x < W; x++) for (let y = 0; y < H; y++) {
      const lon = lon0 + (x + .5) / W * (lon1 - lon0), lat = lat0 + (y + .5) / H * (lat1 - lat0);
      land[x][y] = LAND.some(p => inPoly(lon, lat, p)) && !LAKES.some(p => inPoly(lon, lat, p));
    }
  } else if (name === 'pangea') {
    const ph = [r() * 6, r() * 6, r() * 6];
    for (let x = 0; x < W; x++) for (let y = 0; y < H; y++) {
      const dx = (x - W / 2) / (W * .42), dy = (y - H / 2) / (H * .42), a = Math.atan2(dy, dx);
      const rad = 1 + .22 * Math.sin(3 * a + ph[0]) + .15 * Math.sin(5 * a + ph[1]) + .08 * Math.sin(9 * a + ph[2]);
      land[x][y] = Math.hypot(dx, dy) < rad * .95;
    }
  } else if (name === 'mars') {
    const cr = []; for (let i = 0; i < 9; i++) cr.push({ x: r() * W, y: r() * H, r: 4 + r() * 8 });
    for (let x = 0; x < W; x++) for (let y = 0; y < H; y++) {
      const edge = Math.min(x, y, W - 1 - x, H - 1 - y) > 1;
      const hole = cr.some(c => Math.hypot(x - c.x, (y - c.y) * 1.2) < c.r);
      land[x][y] = edge && !hole;
    }
  } else { // random
    const bl = []; for (let i = 0; i < 8; i++) bl.push({ x: r() * W, y: r() * H, r: 9 + r() * 12 });
    for (let x = 0; x < W; x++) for (let y = 0; y < H; y++) {
      let m = 9; for (const b of bl) m = Math.min(m, Math.hypot(x - b.x, (y - b.y) * 1.1) / b.r);
      const n = (Math.sin(x * .55 + 1) + Math.cos(y * .7) + Math.sin((x + y) * .35)) * .07;
      land[x][y] = m + n < .85;
    }
  }
  return { W, H, land };
}
